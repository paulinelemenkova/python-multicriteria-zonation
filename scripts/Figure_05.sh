#!/bin/bash

set -e
REG="-R26.0/31.0/39.4/42.1"
export GMT_DATA_SERVER=oceania GMT_AUTO_DOWNLOAD=on
gmt set GMT_AUTO_DOWNLOAD on GMT_DATA_SERVER oceania >/dev/null 2>&1 || true

gmt grdcut @earth_relief_03s $REG -Gdem_native.nc=nf
gmt grdsample dem_native.nc -Gdem_fine.nc -I0.0015 $REG
gmt grdgradient dem_fine.nc -Nt1 -A315/45 -Gshade_fine.nc
gmt makecpt -Cgray -T-1.2/1.2/0.05 -Z > gray.cpt

mkdir -p ann && cd ann
BASE="https://data.chc.ucsb.edu/products/CHIRPS-2.0/global_annual/tifs"
for y in 2015 2016 2017 2018 2019 2020 2021 2022 2023 2024; do
  gdalwarp -q -overwrite -te 26.0 39.4 31.0 42.1 -tr 0.01 0.01 -r bilinear -dstnodata -9999 \
    "/vsicurl/${BASE}/chirps-v2.0.${y}.tif" "y${y}.tif" &
done
wait
python3 - <<'PY'
import glob, numpy as np, rasterio
files = sorted(glob.glob('y*.tif'))
prof=None; stack=[]
for f in files:
    with rasterio.open(f) as src:
        arr = src.read(1).astype('float32'); nod = src.nodata
        if prof is None: prof = src.profile
        stack.append(np.where(arr==nod, np.nan, arr))
stack = np.stack(stack,0)
mean = np.nanmean(stack,0)
prof.update(dtype='float32', nodata=-9999.0, count=1)
out = np.where(np.isnan(mean), -9999.0, mean)
with rasterio.open('precip_mean.tif','w',**prof) as dst: dst.write(out,1)
print(f"{stack.shape[0]} years averaged; range {np.nanmin(mean):.0f}-{np.nanmax(mean):.0f} mm/yr")
PY
cd ..
gmt grdconvert ann/precip_mean.tif precip_ll.nc=nf

GB="https://media.githubusercontent.com/media/wmgeolab/geoBoundaries/main/releaseData/gbOpen/TUR/ADM1/geoBoundaries-TUR-ADM1.geojson"
curl -sfL --max-time 150 -o tur.geojson "$GB"
